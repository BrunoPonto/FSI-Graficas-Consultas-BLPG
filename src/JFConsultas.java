    private void BVesesMedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BVesesMedActionPerformed
        String query = "SELECT * FROM (\n"
                + "    SELECT fecha,\n"
                + "           ROUND(AVG(nvl_glucosa), 1) AS promedio_glucosa,\n"
                + "           MIN(nvl_glucosa) AS minima,\n"
                + "           MAX(nvl_glucosa) AS maxima\n"
                + "    FROM mediciones\n"
                + "    WHERE pacientes_curp = 'pals070827b'\n"
                + "    GROUP BY fecha\n"
                + "    ORDER BY fecha DESC\n"
                + "    LIMIT 15\n"
                + ") AS ultimos\n"
                + "ORDER BY fecha ASC;";

        datos = cnx.consultar(query);

        series.clear();
        series.add("Promedio");
        series.add("Mínima");
        series.add("Máxima");

        PGrafica.removeAll();
        PGrafica.setLayout(new java.awt.BorderLayout());
        chart = new GraficaXY("Niveles de Glucosa por Día",
                "Fecha", "Nivel de Glucosa (mg/dL)", series, datos);
        PGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        PGrafica.revalidate();
        PGrafica.repaint();

        cnx.entablar(query, TQuery, 120, 120, 80, 80);

    }//GEN-LAST:event_BVesesMedActionPerformed

